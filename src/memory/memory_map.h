#ifndef SF2_RECON_MEMORY_MAP_H
#define SF2_RECON_MEMORY_MAP_H

#include <stdint.h>

/* MAME sf2eb main_map addresses, not host-process pointers. */
#define SF2_MAINCPU_ROM_START UINT32_C(0x000000)
#define SF2_MAINCPU_REGION_SIZE UINT32_C(0x400000)
#define SF2_MAINCPU_LOADED_SIZE UINT32_C(0x100000)
#define SF2_INPUT_IN1_START UINT32_C(0x800000)
#define SF2_INPUT_IN1_END UINT32_C(0x800007)
#define SF2_DIP_INPUT_START UINT32_C(0x800018)
#define SF2_DIP_INPUT_END UINT32_C(0x80001f)
#define SF2_COIN_CONTROL_START UINT32_C(0x800030)
#define SF2_COIN_CONTROL_END UINT32_C(0x800037)
#define SF2_CPS_A_REGISTERS_START UINT32_C(0x800100)
#define SF2_CPS_A_REGISTERS_END UINT32_C(0x80013f)
#define SF2_CPS_B_REGISTERS_START UINT32_C(0x800140)
#define SF2_CPS_B_REGISTERS_END UINT32_C(0x80017f)
#define SF2_SOUND_LATCH_START UINT32_C(0x800180)
#define SF2_SOUND_LATCH_END UINT32_C(0x800187)
#define SF2_SOUND_TIMER_START UINT32_C(0x800188)
#define SF2_SOUND_TIMER_END UINT32_C(0x80018f)
#define SF2_GFX_RAM_START UINT32_C(0x900000)
#define SF2_GFX_RAM_END UINT32_C(0x92ffff)
#define SF2_GFX_RESET_CLEAR_START UINT32_C(0x900000)
#define SF2_GFX_RESET_CLEAR_END UINT32_C(0x903fff)
#define SF2_MAIN_RAM_START UINT32_C(0xff0000)
#define SF2_MAIN_RAM_END UINT32_C(0xffffff)

/* MAME cps1_6b IN2 masks; no CPU address is asserted here. */
#define SF2_IN2_P1_SHORT_MASK UINT8_C(0x01)
#define SF2_IN2_P1_FORWARD_MASK UINT8_C(0x02)
#define SF2_IN2_P1_ROUNDHOUSE_MASK UINT8_C(0x04)
#define SF2_IN2_P2_SHORT_MASK UINT8_C(0x10)
#define SF2_IN2_P2_FORWARD_MASK UINT8_C(0x20)
#define SF2_IN2_P2_ROUNDHOUSE_MASK UINT8_C(0x40)

#endif
